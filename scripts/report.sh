#!/usr/bin/env bash
# Write a machine-generated inventory of artifacts/ to artifacts/logs/INVENTORY.md.
#
# It deliberately does NOT touch docs/TEST-REPORT.md: that document is curated
# by hand (it holds the measured tables and evidence), and overwriting it
# destroyed content once. Generated inventories belong in artifacts/, which is
# git-ignored.
set -o pipefail
cd "$(dirname "$0")/.." || exit 1

{
  echo "# artifacts inventory"
  echo
  echo "_Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ) by scripts/report.sh (git-ignored)._"
  echo
  echo "## Latest command records"
  echo
  for f in artifacts/logs/*.log; do
    [ -e "$f" ] || continue
    echo "- \`$f\`: $(stat -f '%z bytes' "$f")"
    echo '  ```text'
    grep -E "Test Suite|Test Case.*(passed|failed)|BUILD|error:|TEST " "$f" | tail -6 | sed 's/^/  /'
    echo '  ```'
  done
  echo
  echo "## Capture evidence"
  echo
  find artifacts/captures -type f \( -name "*.png" -o -name "*.sha256" \) 2>/dev/null | sort | while read -r x; do
    echo "- \`$x\`" 
  done
  echo
  echo "## Status (current)"
  echo
  echo "| Phase | Status | Evidence |"
  echo "|---|---|---|"
  echo "| P0 environment | see docs/ENVIRONMENT.md | probe log |"
  echo "| P0 project gen | blocked without Xcode | — |"
  echo "| P1..P7 | pending toolchain | — |"
  echo
  echo "_This report is regenerated by \`scripts/report.sh\`._"
} > artifacts/logs/INVENTORY.md
echo "wrote artifacts/logs/INVENTORY.md (docs/TEST-REPORT.md is curated by hand)"